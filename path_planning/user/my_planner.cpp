// ---------------------------------------------------------------------
// 셀의 실제 크기(월드 단위, 예: 미터). 기본은 1x1 정사각형.
//   지금은 격자 인덱스(x,y)로만 다루지만, 비용은 이 실제 크기로 잰다.
//   → 나중에 로봇 크기에 맞춰 직사각형으로 바꿔도(예: w=0.40, h=0.25)
//     탐색 로직은 그대로 두고 이 값만 바꾸면 된다.
// ---------------------------------------------------------------------
struct CellSize {
    double w = 1.0;   // 셀 한 칸의 가로 실제 길이
    double h = 1.0;   // 셀 한 칸의 세로 실제 길이
};

// 인접한 두 셀 사이 한 스텝의 "실제" 이동 비용.
//   가로 이동 : w
//   세로 이동 : h
//   대각선    : sqrt((dx*w)^2 + (dy*h)^2)
//               정사각형(w=h=1)이면 대각선은 sqrt(2)로 자연히 떨어진다.
// dx,dy 를 그대로 넣어 유클리드로 계산하므로, 직선/대각선을 따로
// 분기하지 않고 정사각형이든 직사각형이든 한 식으로 처리된다.
static double stepCost(Cell from, Cell to, CellSize cell = CellSize{}) {
    double dx = std::abs(from.x - to.x) * cell.w;
    double dy = std::abs(from.y - to.y) * cell.h;
    return std::sqrt(dx * dx + dy * dy);
}

// ---------------------------------------------------------------------
// 가변 셀(Node): 격자 위의 한 칸을 "탐색 중 상태"까지 담아 표현한다.
//   - pos    : 격자 좌표 (탐색 내내 고정, 불변)
//   - g, h, f: 비용 값. 더 짧은 경로를 발견하면 계속 갱신된다 → "가변".
//              g = 시작점에서 여기까지 실제 이동 비용
//              h = 여기서 목표까지의 추정 비용(휴리스틱)
//              f = g + h  (탐색 우선순위)
//   - parent : 이 칸에 도달한 직전 노드의 인덱스. 경로를 거꾸로
//              되짚어 복원할 때 쓴다. 부모가 없으면 -1(시작 노드).
// 나중에 std::vector<Node> 로 노드 풀을 만들어 인덱스로 참조하면
// 포인터/이터레이터 무효화 걱정 없이 안전하게 확장할 수 있다.
// ---------------------------------------------------------------------
struct Node {
    Cell   pos;
    double g = 0.0;
    double h = 0.0;
    double f = 0.0;
    int    parent = -1;
};

// 가변 셀 하나를 만들어 반환하는 팩토리 함수.
//   f 는 g+h 로 자동 계산되므로 따로 넘기지 않는다.
static Node makeNode(Cell pos, double g = 0.0, double h = 0.0, int parent = -1) {
    Node n;
    n.pos    = pos;
    n.g      = g;
    n.h      = h;
    n.f      = g + h;   // f 는 항상 g와 h로부터 유도
    n.parent = parent;
    return n;
}

